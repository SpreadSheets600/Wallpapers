#!/usr/bin/env python3
"""Generate the root README.md and one README.md per category.

Usage:
    python3 scripts/build_readme.py
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMAGES = ROOT / "Wallpapers"
SUFFIXES = (".jpg", ".jpeg", ".png", ".webp", ".gif")
USER = "SpreadSheets600"
REPO = f"https://github.com/{USER}/Wallpapers"
SITE = f"https://{USER.lower()}.github.io/Wallpapers/"


def categories() -> list[tuple[str, list[str], int]]:
    result = []
    for path in sorted(p for p in IMAGES.iterdir() if p.is_dir()):
        images = sorted(
            (f.name for f in path.iterdir() if f.suffix.lower() in SUFFIXES),
            key=lambda name: (0, int(Path(name).stem)) if Path(name).stem.isdigit() else (1, name),
        )
        if not images:
            continue
        size = sum((path / name).stat().st_size for name in images)
        result.append((path.name, images, size))
    return result


def build_root(cats) -> str:
    total = sum(len(images) for _, images, _ in cats)
    size = sum(s for _, _, s in cats) / 1048576
    updated = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    rows = [
        f"| <img src=\"Wallpapers/{name}/{images[0]}\" width=\"180\" alt=\"{name}\"> "
        f"| **[{name}](Wallpapers/{name}/)** | {len(images)} | {s / 1048576:.1f} MB |"
        for name, images, s in cats
    ]

    return f"""# wallpapers

A hand-picked wallpaper collection, sorted by what is in the image and then by
colour, so every folder flows from one palette into the next.

`{total}` images &middot; `{size:.0f} MB` &middot; `{len(cats)}` categories &middot; last rebuilt `{updated}`

Browse the gallery: **[{SITE.replace('https://', '')}]({SITE})**

## categories

| preview | collection | images | size |
|---|---|---|---|
{chr(10).join(rows)}

## layout

```text
Wallpapers/<Category>/<n>.<ext>   the images, numbered in colour order
index.html, styles.css            gallery generated by scripts/build_site.py
scripts/                          maintenance scripts
```

## adding wallpapers

```bash
git clone {REPO}.git
cd Wallpapers

# drop files into a category (or make a new folder)
cp ~/Downloads/*.jpg Wallpapers/Anime/

python3 scripts/organize.py     # HEIC -> JPEG, renumber loose files
python3 scripts/build_readme.py # refresh READMEs
python3 scripts/build_site.py   # refresh the gallery
git add -A && git commit -m "feat: add wallpapers" && git push
```

Sorting a new image into the right folder is manual on purpose: pick the
category it belongs to, then run `scripts/organize.py` to give it a number.

## credits

I do not own any of these images. Everything here belongs to the respective
artists and is collected for personal desktop use. If you are the owner of an
image and want it removed, open an issue and it will be taken down.
"""


def build_category(name: str, images: list[str]) -> str:
    size = sum((IMAGES / name / image).stat().st_size for image in images) / 1048576
    rows = []
    for start in range(0, len(images), 4):
        chunk = images[start:start + 4]
        cells = [
            f'<a href="{image}"><img src="{image}" width="220" alt="{name} {image}"></a>'
            for image in chunk
        ]
        cells += [""] * (4 - len(cells))
        rows.append("| " + " | ".join(cells) + " |")

    return f"""# {name}

[&larr; all categories](../README.md)

`{len(images)}` images &middot; `{size:.1f} MB`

|  |  |  |  |
|---|---|---|---|
{chr(10).join(rows)}

Every wallpaper belongs to its original creator. See the
[main README](../README.md#credits) for credits and takedown requests.
"""


def main() -> None:
    cats = categories()
    (ROOT / "README.md").write_text(build_root(cats), encoding="utf-8")
    for name, images, _ in cats:
        (IMAGES / name / "README.md").write_text(build_category(name, images), encoding="utf-8")
    print(f"wrote README.md + {len(cats)} category READMEs")


if __name__ == "__main__":
    main()
